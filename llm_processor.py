import os
from google import genai
from dotenv import load_dotenv

load_dotenv()

class LLMProcessor:
    def __init__(self):
        self.client = genai.Client(api_key=os.getenv("GEMINI_API_KEY"))
        # 의원님께서 결제 설정을 완료하셨으므로 가용한 가장 강력한 Pro 모델을 유지합니다.
        self.model_name = 'gemini-2.5-pro' 

    def generate_report(self, news_data):
        prompt = self._build_prompt(news_data)
        
        response = self.client.models.generate_content(
            model=self.model_name,
            contents=prompt
        )
        return response.text

    def _build_prompt(self, news_data):
        news_summary = ""
        for cat, items in news_data.items():
            news_summary += f"\n### 섹션: {cat}\n"
            # 대량의 데이터를 AI에게 효과적으로 전달 (정치 섹션 대폭 확대)
            limit = 200 if "정치" in cat else 50
            for item in items[:limit]:
                news_summary += f"- 제목: {item['title']}\n  요약: {item['description']}\n  링크: {item['link']}\n"

        prompt = f"""
[핵심 정체성 및 전략 기조]
- 모든 보고는 "본 보고서는 지난 24시간 동안 발생한 방대한 뉴스 데이터를 전수 조사하여, 그중 정무적 파급력이 가장 큰 핵심 기사들을 엄밀히 선별하고 카테고리별로 심층 분석한 결과입니다. 분석의 정확도를 높이기 위해 복수의 언론 보도를 교차 검증하고 AI 엔진을 통한 구조적 분석을 거쳤으나, 정무적 판단이 중요하게 작용하는 사안에 대해서는 반드시 실무적인 직접 확인을 병행해 주시길 부탁드립니다."로 시작하십시오.
- **절대 생략 및 요약 금지 (CRITICAL)**: "지면 관계상 요약한다"거나 "나머지는 생략한다"는 식의 메시지를 절대 남기지 마십시오. 모든 10가지 인물과 10가지 현안은 동일하게 깊이 있고 정교한 분량으로 끝까지 작성해야 합니다.
- **외유내강(外柔內剛)의 분석**: 어조는 부드럽고 정중한 보좌진의 경어체를 유지하되, 내용은 정부와 여당(민주당)의 실정을 가장 날카롭게 파헤치는 **'공격의 논리'**를 담으십시오.
- **당내 문제 로우키(Low-key) 전략**: 우리 당(국민의힘) 내부의 갈등이나 민감한 당내 현안에 대해서는 선명한 비판보다는 "상황을 예밀하게 주시하며 한 걸음 물러나 신중히 대응하는 것이 실익일 듯합니다"와 같이 **로우키 포지셔닝**을 제언하십시오.
- **정무적 중량감 우선**: 뉴스 빈도뿐만 아니라 **'정치적 파급력'**이 큰 인물과 이슈를 우선 선별하십시오. (예: 한동훈, 장동혁, 제명, 정계 개편 등 'HOT'한 이슈 최우선)

[수집된 뉴스 데이터 요약]
{news_summary}

[보고서 구성 및 지침]

1.  **Ⅰ. 오늘의 주요 인물 TOP 10 브리핑 (국내 7 : 해외 3 필수)**:
    - **가독성 및 금지사항**: **절대로 `---`나 `***` 같은 마크다운 구분선을 사용하지 마십시오.** 문장 사이의 불필요한 다중 공백을 제거하십시오.
    - **쿼터 준수**: 국내 핵심 정치 인물 7인과 **해외 주요 인물 3인**을 **반드시** 포함하십시오.
    - **요소별 여백**: 모든 요소 사이에 반드시 빈 줄(Blank Line)을 넣되, 구분선은 쓰지 마십시오.
    - **형식**: 
      **인물 이름 (소속)**
      
      * **[동향 분석]**
      * [동향 상세 내용 - 문장 끝에 반드시 `<sup><a href="URL" target="_blank">[N]</a></sup>` 첨부]
      
      * **[보좌진의 생각]**
      * [전략적 제언]

2.  **Ⅱ. 주요 국정 및 정치 현안 (TOP 10 심층 분석)**:
    - **구조 및 금지사항**: **섹션 구분 시 `---` 사용을 엄격히 금지합니다.** 오직 제목과 빈 줄로만 구분하십시오.
    - **출처 증명**: **[현안 분석], [민주당의 입장], [국민의힘의 입장] 등 모든 분석 섹션의 문장 끝에 반드시 근거 뉴스 주석 `<sup><a href="URL" target="_blank">[N]</a></sup>`을 다십시오.**
    - **가독성**: 모든 분석 요소는 좌측 정렬을 전제로, 단어 사이 간격이 벌어지지 않도록 자연스럽게 작성하십시오.
    - **형식**:
      ### 1. 현안 제목
      
      * **[현안 분석]**
      * [이슈의 핵심 및 배경 - 주석 필수]
      
      * **[민주당의 입장]**
      * [정치적 공세 논리 - 주석 필수]
      
      * **[국민의힘의 입장]**
      * [우리 당의 대응 기조 - 주석 필수]
      
      * **[여론의 흐름]**
      * [객관적 데이터 분석]
      
      * **[정무적 제언]**
      * [전략적 대응 논리]

3.  **Ⅲ. 문화체육관광위원회(상임위) 정책 전략 (5대 이슈)**:
    - **가독성 원칙**: 상임위 현안 또한 위와 동일하게 충분한 빈 줄을 사용하여 정책 대안을 상세히 기술하십시오.

4.  **Ⅳ. 청년/장애인 섹션 (이소희의 목소리)**:
    - **최근 14일간의 동향 포함**: 이 섹션은 최근 2주간의 흐름을 반영하여 장기적 관점의 정책 대안을 제시하십시오. 역시 요소 간 빈 줄 사용은 필수입니다.

5.  **직접 뉴스 링크**: (문장 끝에 `<sup><a href="뉴스링크" target="_blank">[N]</a></sup>` 형식 사용)

6.  **하단 필수 안내 문구**:
    - **[여론 지형 안내]**: 본 보고서는 방대한 뉴스 데이터와 여론 흐름을 분석한 결과입니다.
    - **[전략 참고 안내]**: 본 제언은 보좌진의 전략적 판단에 따른 참고용 정보입니다.
"""
        return prompt
